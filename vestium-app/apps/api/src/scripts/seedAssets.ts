// ─── Seed runner ──────────────────────────────────────────────────────────────

async function seed() {
  console.log(`Seeding ${assets.length} proxy assets...`);
  let inserted = 0;
  let skipped = 0;

  for (const asset of assets) {
    const result = await sql`
      INSERT INTO proxy_assets (
        symbol_code, standard, category, description,
        tags, schema_refs, svg_path, licence, attribution
      )
      VALUES (
        ${asset.symbol_code},
        ${asset.standard},
        ${asset.category},
        ${asset.description},
        ${asset.tags},
        ${asset.schema_refs},
        ${asset.svg_path},
        ${asset.licence},
        ${asset.attribution}
      )
      ON CONFLICT (symbol_code, standard) DO NOTHING
      RETURNING id
    `;
    if (result.length > 0) {
      inserted++;
    } else {
      skipped++;
    }
  }

  console.log(`Done: ${inserted} inserted, ${skipped} already present.`);
  process.exit(0);
}

seed().catch((err) => {
  console.error('Seed failed:', err);
  process.exit(1);
});
