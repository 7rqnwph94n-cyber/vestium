import type { ThemeConfig, TrainingLesson, TrainingQuestion, TrainingStage } from './types';

const splitIntoSentences = (text: string): string[] =>
  text
    .split(/(?<=[.!?])\s+/)
    .map((segment) => segment.trim())
    .filter(Boolean);

const inferSituationHook = (lesson: TrainingLesson): string | undefined => {
  if (lesson.situationHook?.trim()) return lesson.situationHook.trim();
  const workedSentences = splitIntoSentences(lesson.workedExample);
  const lead = workedSentences.slice(0, 2).join(' ');
  const objective = lesson.objective.trim().replace(/\.$/, '');
  if (!lead) return undefined;
  return `${lead} This matters because ${objective.charAt(0).toLowerCase()}${objective.slice(1)}.`;
};

const APPLICATION_HINTS = [
  'given',
  'scenario',
  'customer',
  'fault',
  'fails',
  'best first',
  'next step',
  'you should',
  'what should',
  'first action',
  'most appropriate',
  'most likely',
  'based on'
];

const inferQuestionIntent = (question: TrainingQuestion): 'application' | 'knowledge' => {
  if (question.intent === 'application' || question.intent === 'knowledge') {
    return question.intent;
  }
  const text = `${question.prompt} ${question.explanation}`.toLowerCase();
  return APPLICATION_HINTS.some((hint) => text.includes(hint)) ? 'application' : 'knowledge';
};

const normalizeLesson = (lesson: TrainingLesson): TrainingLesson => ({
  ...lesson,
  situationHook: inferSituationHook(lesson),
  quiz: lesson.quiz.map((question) => ({
    ...question,
    intent: inferQuestionIntent(question)
  }))
});

const normalizeThemeConfig = (theme: ThemeConfig): ThemeConfig => ({
  ...theme,
  curriculum: theme.curriculum.map((stage) => ({
    ...stage,
    lessons: stage.lessons.map(normalizeLesson),
    test: stage.test.map((question) => ({
      ...question,
      intent: inferQuestionIntent(question)
    }))
  })),
  placementAssessment: theme.placementAssessment
    ? {
        ...theme.placementAssessment,
        questions: theme.placementAssessment.questions.map((question) => ({
          ...question,
          intent: inferQuestionIntent(question)
        }))
      }
    : undefined
});

// ─── Static module registry ───────────────────────────────────────────────────
// Intentionally empty — all production modules are generated by the backend
// pipeline and registered at runtime via registerDynamicModule().
// Legacy CurricuSmith v1 static modules have been removed.


export const modulesRegistry: Record<string, ThemeConfig> = {};

// ─── Lazy-load legacy demo module (keeps it out of the initial bundle) ───────
const _readyCallbacks: (() => void)[] = [];
let _staticReady = false;

/** Register a callback for when static modules finish loading. Fires immediately if already ready. */
export function onStaticModulesReady(cb: () => void): void {
  if (_staticReady) cb();
  else _readyCallbacks.push(cb);
}

void import('../../data/weldingmetalTheme').then(({ weldingmetalThemeConfig }) => {
  modulesRegistry.weldingmetal = weldingmetalThemeConfig as unknown as ThemeConfig;
  _staticReady = true;
  _readyCallbacks.forEach((fn) => fn());
  _readyCallbacks.length = 0;
});

export const DEFAULT_THEME_ID = '';

export const defaultCurriculum: TrainingStage[] = [];

export const getDefaultStageById = (_stageId: number): TrainingStage | undefined => undefined;

// ─── Dynamic module registry (Studio preview — populated at runtime) ──────────

export const dynamicModulesRegistry: Record<string, ThemeConfig> = {};

export function registerDynamicModule(config: ThemeConfig): void {
  dynamicModulesRegistry[config.id] = normalizeThemeConfig(config);
}
