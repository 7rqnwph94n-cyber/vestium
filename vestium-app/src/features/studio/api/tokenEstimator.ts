// ─── Token & cost estimator ──────────────────────────────────────────────────
// Pre-generation estimates shown to users BEFORE any API calls.
// Post-generation actual cost computed from step-level token counts.
//
// Estimates calibrated against real pipeline runs (TM-01 baseline, March 2026):
//   Blueprint ~25k tokens, Stage ~20k, StageTest ~10k, Missions ~8k,
//   PlacementAssessment ~27k, SourceAttribution ~4k, ThemeShell ~3k.
// Each step includes: system prompt, user prompt, tool_use overhead, and
// a critique call (~40% of main call tokens).  Repair calls are conditional
// and excluded from the estimate but covered by the ±30% variance band.

export interface TokenEstimate {
  stepKey: string;
  label: string;
  inputTokens: number;
  outputTokens: number;
  provider: 'anthropic' | 'gemini';
}

export interface CostEstimate {
  steps: TokenEstimate[];
  totalInputTokens: number;
  totalOutputTokens: number;
  anthropicInputTokens: number;
  anthropicOutputTokens: number;
  geminiInputTokens: number;
  geminiOutputTokens: number;
  estimatedUsdCost: number;
}

// ─── Pricing (March 2026) ────────────────────────────────────────────────────
// Anthropic claude-sonnet-4-6: $3/MTok input, $15/MTok output
// Gemini 2.5 Flash:            $0.15/MTok input, $0.60/MTok output
// (Check anthropic.com/pricing and ai.google.dev/pricing for current rates)

const ANTHROPIC_INPUT_PER_TOKEN  = 3 / 1_000_000;
const ANTHROPIC_OUTPUT_PER_TOKEN = 15 / 1_000_000;
const GEMINI_INPUT_PER_TOKEN     = 0.15 / 1_000_000;
const GEMINI_OUTPUT_PER_TOKEN    = 0.60 / 1_000_000;

// Steps routed to Gemini; all others use Anthropic.
const GEMINI_STEP_KEYS = new Set([
  'domainSurvey', 'coherencePass', 'factCheckG',
  // Critique calls route to Gemini when PIPELINE_PROVIDER_CRITIQUE=gemini (default)
  'critique_blueprint', 'critique_missions',
]);

function isGeminiStep(key: string): boolean {
  if (GEMINI_STEP_KEYS.has(key)) return true;
  // Critique steps for stages/tests are also Gemini
  if (key.startsWith('critique_stage_') || key.startsWith('critique_test_')) return true;
  return false;
}

// ─── Pre-generation estimate ─────────────────────────────────────────────────
// Token counts are calibrated against actual pipeline runs.
// "Input" = prompt tokens sent to the model.
// "Output" = completion tokens generated by the model.
// Each main step has a paired critique call (~40% of main tokens) included below.

export function estimateCost(
  stageCount: number,
  lessonsPerStage: number,
  missionCount: number,
  sourceReferenceCount: number,
  objectivesCount: number
): CostEstimate {
  const steps: TokenEstimate[] = [];

  // Domain survey (Gemini) — regulatory context + ground truth extraction
  steps.push({
    stepKey: 'domainSurvey',
    label: 'Domain survey (Gemini)',
    inputTokens: 2800,
    outputTokens: 2400,
    provider: 'gemini',
  });

  // Blueprint — full regulatory context + domain survey injected
  steps.push({
    stepKey: 'blueprint',
    label: 'Blueprint (1 call + critique)',
    inputTokens: 16000 + stageCount * 600,
    outputTokens: 7000 + stageCount * 800,
    provider: 'anthropic',
  });

  // Stage lessons — 1 call per stage; each includes blueprint, regulatory context, domain survey
  for (let i = 1; i <= stageCount; i++) {
    steps.push({
      stepKey: `stage_${i}`,
      label: `Stage ${i} lessons (1 call + critique)`,
      inputTokens: 12000 + lessonsPerStage * 400,
      outputTokens: 6000 + lessonsPerStage * 1800,
      provider: 'anthropic',
    });
  }

  // Stage tests — 1 call per stage; includes lesson summaries + quiz prompts
  for (let i = 1; i <= stageCount; i++) {
    steps.push({
      stepKey: `test_${i}`,
      label: `Stage ${i} test (1 call + critique)`,
      inputTokens: 6000 + lessonsPerStage * 200,
      outputTokens: 3500,
      provider: 'anthropic',
    });
  }

  // Missions — all stage titles + lesson summaries
  steps.push({
    stepKey: 'missions',
    label: 'Missions (1 call + critique)',
    inputTokens: 4000 + stageCount * lessonsPerStage * 120,
    outputTokens: 3000 + missionCount * 250,
    provider: 'anthropic',
  });

  // Placement assessment — needs all test content + lesson summaries
  steps.push({
    stepKey: 'placementAssessment',
    label: 'Placement assessment (1 call + critique)',
    inputTokens: 16000 + stageCount * lessonsPerStage * 200,
    outputTokens: 8000,
    provider: 'anthropic',
  });

  // Lesson mission map
  steps.push({
    stepKey: 'lessonMissionMap',
    label: 'Lesson → mission map (1 call)',
    inputTokens: 1200 + stageCount * lessonsPerStage * 80 + missionCount * 100,
    outputTokens: 1000 + stageCount * lessonsPerStage * 40,
    provider: 'anthropic',
  });

  // Source attribution
  steps.push({
    stepKey: 'sourceAttribution',
    label: 'Source attribution (1 call)',
    inputTokens: 2000 + stageCount * lessonsPerStage * 60 + missionCount * 80 + sourceReferenceCount * 150,
    outputTokens: 1800 + (stageCount * lessonsPerStage + missionCount) * 40,
    provider: 'anthropic',
  });

  // Source discovery
  steps.push({
    stepKey: 'sourceDiscovery',
    label: 'Source discovery (1 call)',
    inputTokens: 1200 + objectivesCount * 80 + sourceReferenceCount * 100,
    outputTokens: 800,
    provider: 'anthropic',
  });

  // Coherence pass (Gemini) — cross-stage contradiction detection
  steps.push({
    stepKey: 'coherencePass',
    label: 'Coherence pass (Gemini)',
    inputTokens: 6000 + stageCount * lessonsPerStage * 200,
    outputTokens: 4000,
    provider: 'gemini',
  });

  // Fact-check — Anthropic (4A) + Gemini (4G)
  steps.push({
    stepKey: 'factCheckA',
    label: 'Fact-check Anthropic',
    inputTokens: 4000 + stageCount * lessonsPerStage * 100 + missionCount * 120,
    outputTokens: 4000,
    provider: 'anthropic',
  });
  steps.push({
    stepKey: 'factCheckG',
    label: 'Fact-check Gemini',
    inputTokens: 4000 + stageCount * lessonsPerStage * 100 + missionCount * 120,
    outputTokens: 4000,
    provider: 'gemini',
  });

  // Theme shell
  steps.push({
    stepKey: 'themeShell',
    label: 'Theme shell (1 call)',
    inputTokens: 1800,
    outputTokens: 1000,
    provider: 'anthropic',
  });

  // Simulator design + fault/reference + builder/capstone (3 split calls)
  steps.push({
    stepKey: 'simulatorDesign',
    label: 'Simulator design (1 call)',
    inputTokens: 2000 + stageCount * 400,
    outputTokens: 2500,
    provider: 'anthropic',
  });
  steps.push({
    stepKey: 'faultAndReference',
    label: 'Fault scenarios + reference cards',
    inputTokens: 2200 + stageCount * 300,
    outputTokens: 3000,
    provider: 'anthropic',
  });
  steps.push({
    stepKey: 'builderAndCapstone',
    label: 'Builder exercises + capstone',
    inputTokens: 2000 + stageCount * 300,
    outputTokens: 2500,
    provider: 'anthropic',
  });

  // Aggregate
  let anthropicIn = 0, anthropicOut = 0, geminiIn = 0, geminiOut = 0;
  for (const s of steps) {
    if (s.provider === 'gemini') { geminiIn += s.inputTokens; geminiOut += s.outputTokens; }
    else { anthropicIn += s.inputTokens; anthropicOut += s.outputTokens; }
  }

  const estimatedUsdCost =
    anthropicIn * ANTHROPIC_INPUT_PER_TOKEN +
    anthropicOut * ANTHROPIC_OUTPUT_PER_TOKEN +
    geminiIn * GEMINI_INPUT_PER_TOKEN +
    geminiOut * GEMINI_OUTPUT_PER_TOKEN;

  return {
    steps,
    totalInputTokens: anthropicIn + geminiIn,
    totalOutputTokens: anthropicOut + geminiOut,
    anthropicInputTokens: anthropicIn,
    anthropicOutputTokens: anthropicOut,
    geminiInputTokens: geminiIn,
    geminiOutputTokens: geminiOut,
    estimatedUsdCost,
  };
}

export function formatUsd(amount: number): string {
  if (amount < 0.01) return '<$0.01';
  return `~$${amount.toFixed(2)}`;
}

// ─── Post-generation actual cost ─────────────────────────────────────────────
// Uses step-level `tokensUsed` (combined input + output + critique) to compute
// actual cost.  Since we don't have the input/output breakdown from the pipeline,
// we use measured ratios: Anthropic steps average 65% input / 35% output,
// Gemini steps average 55% input / 45% output.

const ANTHROPIC_ACTUAL_RATIO_IN = 0.65;
const ANTHROPIC_ACTUAL_RATIO_OUT = 0.35;
const GEMINI_ACTUAL_RATIO_IN = 0.55;
const GEMINI_ACTUAL_RATIO_OUT = 0.45;

export interface ActualCostEstimate {
  totalTokens: number;
  anthropicTokens: number;
  geminiTokens: number;
  estimatedUsdCost: number;
  breakdown: {
    anthropicInputTokens: number;
    anthropicOutputTokens: number;
    geminiInputTokens: number;
    geminiOutputTokens: number;
  };
}

export function computeActualCost(
  steps: Record<string, { tokensUsed?: number } | undefined>
): ActualCostEstimate {
  let anthropicTokens = 0;
  let geminiTokens = 0;
  for (const [key, step] of Object.entries(steps)) {
    const t = step?.tokensUsed ?? 0;
    if (isGeminiStep(key)) geminiTokens += t;
    else anthropicTokens += t;
  }

  // Split combined tokens using measured ratios
  const aIn = Math.round(anthropicTokens * ANTHROPIC_ACTUAL_RATIO_IN);
  const aOut = Math.round(anthropicTokens * ANTHROPIC_ACTUAL_RATIO_OUT);
  const gIn = Math.round(geminiTokens * GEMINI_ACTUAL_RATIO_IN);
  const gOut = Math.round(geminiTokens * GEMINI_ACTUAL_RATIO_OUT);

  const estimatedUsdCost =
    aIn * ANTHROPIC_INPUT_PER_TOKEN +
    aOut * ANTHROPIC_OUTPUT_PER_TOKEN +
    gIn * GEMINI_INPUT_PER_TOKEN +
    gOut * GEMINI_OUTPUT_PER_TOKEN;

  return {
    totalTokens: anthropicTokens + geminiTokens,
    anthropicTokens,
    geminiTokens,
    estimatedUsdCost,
    breakdown: {
      anthropicInputTokens: aIn,
      anthropicOutputTokens: aOut,
      geminiInputTokens: gIn,
      geminiOutputTokens: gOut,
    },
  };
}
